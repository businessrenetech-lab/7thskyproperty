/**
 * Seeds (or refreshes) the HR offer letter template (HRM Module 3 §15: "Offer Letter should be generated from an
 * approved template"). Recruitment fills the {{fields}} from the offer (services/hrRecruitmentStore.renderOffer);
 * the candidate accepts electronically on /admin/offer/:token. Idempotent by name. Run from the backend dir:
 *   node scripts/seedHrOfferLetter.js
 */
require('dotenv').config();
const sequelize = require('../config/db.config');
const AgreementTemplate = require('../models/AgreementTemplate');

const NAME = 'HR — Offer of Employment';
const V = (k) => `{{${k}}}`;
const F = (key, label, type = 'text') => ({ key, label, type, group: 'Offer', required: true });

const FIELDS = [
  F('candidate_name', 'Candidate name'), F('candidate_address', 'Candidate address'), F('position_title', 'Position'), F('department', 'Department'),
  F('salary', 'Monthly basic salary'), F('employment_type', 'Employment type'), F('probation_months', 'Probation (months)', 'number'),
  F('start_date', 'Start date', 'date'), F('supervisor_name', 'Supervisor'), F('work_location', 'Work location'), F('offer_date', 'Offer date', 'date'),
];

const CONTENT_HTML = `
<p style="text-align:right">${V('offer_date')}</p>
<p><strong>${V('candidate_name')}</strong><br>${V('candidate_address')}</p>
<h2>Offer of employment: ${V('position_title')}</h2>
<p>Dear ${V('candidate_name')},</p>
<p>Following your recent interviews, ${V('company_name')} is pleased to offer you the position of <strong>${V('position_title')}</strong>
in the ${V('department')} department (reference ${V('vacancy_code')}).</p>
<table style="border-collapse:collapse;width:100%;margin:12px 0">
  <tr><td style="padding:6px 8px;border:1px solid #ddd;width:40%">Position</td><td style="padding:6px 8px;border:1px solid #ddd">${V('position_title')}</td></tr>
  <tr><td style="padding:6px 8px;border:1px solid #ddd">Employment type</td><td style="padding:6px 8px;border:1px solid #ddd">${V('employment_type')}</td></tr>
  <tr><td style="padding:6px 8px;border:1px solid #ddd">Monthly basic salary</td><td style="padding:6px 8px;border:1px solid #ddd">${V('salary')}</td></tr>
  <tr><td style="padding:6px 8px;border:1px solid #ddd">Start date</td><td style="padding:6px 8px;border:1px solid #ddd">${V('start_date')}</td></tr>
  <tr><td style="padding:6px 8px;border:1px solid #ddd">Probation period</td><td style="padding:6px 8px;border:1px solid #ddd">${V('probation_months')} months</td></tr>
  <tr><td style="padding:6px 8px;border:1px solid #ddd">Reports to</td><td style="padding:6px 8px;border:1px solid #ddd">${V('supervisor_name')}</td></tr>
  <tr><td style="padding:6px 8px;border:1px solid #ddd">Work location</td><td style="padding:6px 8px;border:1px solid #ddd">${V('work_location')}</td></tr>
</table>
<p>This offer depends on the pre-employment checks already completed remaining valid, and on you providing the documents
HR asks for before your start date. Your full terms of employment will be set out in your employment agreement.</p>
<p>Please accept or decline this offer using the buttons below this letter.</p>
<p>We look forward to welcoming you to Seventh Sky.</p>
<p>Yours sincerely,<br><strong>Human Resources</strong><br>${V('company_name')}</p>`;

(async () => {
  try {
    await sequelize.authenticate();
    const payload = {
      name: NAME, category: 'hr_offer', vertical: 'hr', status: 'active', description: 'Offer letter generated by Recruitment (HRM Module 3 §15).',
      content_html: CONTENT_HTML, fields: FIELDS, signers: [],
    };
    const existing = await AgreementTemplate.findOne({ where: { name: NAME } });
    if (existing) { await existing.update(payload); console.log(`✓ Updated template #${existing.id} "${NAME}"`); }
    else { const t = await AgreementTemplate.create(payload); console.log(`✓ Created template #${t.id} "${NAME}"`); }
    process.exit(0);
  } catch (e) {
    console.error('✗ Seed failed:', e.message);
    process.exit(1);
  }
})();
